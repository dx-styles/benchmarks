import { type Decls, isToken, kebab, type Rule, STATE_SELECTOR, STATES, type Value } from "../scene/ir.ts";
import { cssVarName, tokenList } from "../scene/tokens.ts";

export type Layout = "app" | "single";

/** What a generator gives the harness for one lane. */
export interface LaneSource {
  /** Files relative to the lane directory (usually under `src/`). */
  files: Record<string, string>;
  /** `ui` module path relative to `src/` (without extension) is always `ui`. */
  vite: {
    /** Import lines for vite.config.ts. */
    imports: string[];
    /** Plugin expressions, placed after `react()` in vite.config.ts. */
    plugins: string[];
    /** Plugin expressions the library documents BEFORE `react()`. */
    first?: string[];
    /** Extra top-level config entries (`key: value` text). */
    extra?: string[];
  };
  /** Side-effect imports for src/main.tsx (CSS entry files and the like). */
  mainImports?: string[];
  /** A command to run in the lane before every build (counted in the build time). */
  codegen?: string[];
  /** Directories (relative to the lane) removed before a cold build, besides dist and the Vite cache. */
  cleanDirs?: string[];
}

export const HEADER = (lib: string): string =>
  `// Generated by generators/${lib}.ts from scene/ — do not edit by hand.\n`;

/** A property name as an object key: bare identifier when possible. */
export const key = (name: string): string => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

/** CSS text of a value, with tokens as the given CSS (e.g. `var(--tk-color-accent600)`). */
export const cssValue = (value: Value, varOf: (path: string) => string): string =>
  isToken(value) ? varOf(value.t) : value;

/** Declarations as CSS text lines. */
export const cssDecls = (decls: Decls, varOf: (path: string) => string, indent = "  "): string =>
  Object.entries(decls)
    .map(([prop, value]) => `${indent}${kebab(prop)}: ${cssValue(value, varOf)};`)
    .join("\n");

/** A rule as CSS blocks: `.sel { … }` then `.sel:hover { … }` and so on. */
export const cssRule = (selector: string, rule: Rule, varOf: (path: string) => string): string => {
  const blocks = [`${selector} {\n${cssDecls(rule.decls, varOf)}\n}`];
  for (const state of STATES) {
    const decls = rule.states?.[state];
    if (decls) blocks.push(`${selector}${STATE_SELECTOR[state]} {\n${cssDecls(decls, varOf)}\n}`);
  }
  return blocks.join("\n");
};

/** A rule as nested CSS text (`…; &:hover { … }`), for template-literal libraries. */
export const cssNested = (rule: Rule, varOf: (path: string) => string, indent = "  "): string => {
  const lines = [cssDecls(rule.decls, varOf, indent)];
  for (const state of STATES) {
    const decls = rule.states?.[state];
    if (decls) lines.push(`${indent}&${STATE_SELECTOR[state]} {\n${cssDecls(decls, varOf, `${indent}  `)}\n${indent}}`);
  }
  return lines.join("\n");
};

/** A JS expression for a value: tokens through `exprOf`, literals as strings. */
export const jsValue = (value: Value, exprOf: (path: string) => string): string =>
  isToken(value) ? exprOf(value.t) : JSON.stringify(value);

/** Declarations as a JS object literal body. */
export const jsDecls = (decls: Decls, exprOf: (path: string) => string, indent: string): string =>
  Object.entries(decls)
    .map(([prop, value]) => `${indent}${key(prop)}: ${jsValue(value, exprOf)},`)
    .join("\n");

/**
 * A rule as a JS style object with nested selector keys (`"&:hover"`, or `":hover"`
 * with `selectorPrefix: ""`), the shape most object-style libraries take.
 */
export const jsRule = (
  rule: Rule,
  exprOf: (path: string) => string,
  indent = "  ",
  selectorKey: (selector: string) => string = (s) => `&${s}`,
): string => {
  const lines = [jsDecls(rule.decls, exprOf, indent)];
  for (const state of STATES) {
    const decls = rule.states?.[state];
    if (decls) {
      lines.push(`${indent}${JSON.stringify(selectorKey(STATE_SELECTOR[state]))}: {\n${jsDecls(decls, exprOf, `${indent}  `)}\n${indent}},`);
    }
  }
  return `{\n${lines.filter(Boolean).join("\n")}\n${indent.slice(2)}}`;
};

/** Plain CSS custom property declarations for every token (for libraries without a token primitive). */
export const rootVarDecls = (): Decls =>
  Object.fromEntries(tokenList().map(({ group, name, value }) => [cssVarName(`${group}.${name}`), value]));

/** `var(--tk-<group>-<name>)` for a token path. */
export const plainVar = (path: string): string => `var(${cssVarName(path)})`;

/** The token registry as a nested object literal of `var(--tk-…)` strings. */
export const plainVarObject = (): string => {
  const groups = new Map<string, string[]>();
  for (const { group, name } of tokenList()) {
    const lines = groups.get(group) ?? [];
    lines.push(`    ${key(name)}: ${JSON.stringify(plainVar(`${group}.${name}`))},`);
    groups.set(group, lines);
  }
  return `{\n${[...groups].map(([group, lines]) => `  ${key(group)}: {\n${lines.join("\n")}\n  },`).join("\n")}\n}`;
};

/** Component name of a slot: `iconButton` -> `IconButton`. */
export const componentName = (slot: string): string => slot.charAt(0).toUpperCase() + slot.slice(1);
